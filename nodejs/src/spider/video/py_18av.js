// 单次取页：框架 req 优先（App 蜘蛛运行时无全局 fetch），原生 fetch 仅作有 fetch 环境的第二通道。
// responseType:'text' + 恒等 transform 防 axios 把 JSON 回包自动解析成对象。
async function rawGet(url, headers, timeoutMs) {
  const to = timeoutMs || 20000;
  try {
    const r = await req.get(url, {
      headers, timeout: to, responseType: 'text', transformResponse: [(d) => d], validateStatus: () => true,
    });
    if (r && r.status >= 200 && r.status < 300) {
      const d = r.data;
      if (typeof d === 'string') return d;
      if (d) return JSON.stringify(d);
    }
    return '';
  } catch (e) { /* 换 fetch 通道 */ }
  try {
    if (typeof fetch === 'function') {
      const r = await fetch(url, { headers, signal: AbortSignal.timeout(to) });
      if (r.ok) return await r.text();
    }
  } catch (e) { /* ignore */ }
  return '';
}

