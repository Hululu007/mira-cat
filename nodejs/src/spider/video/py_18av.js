// 单域取页：命中门页时取 gate URL（其 JS 含 Cookie 名），更新 ageCookie 后重试一次
async function getHtmlForOrigin(origin, path, timeoutMs) {
  const url = origin + path;
  let html = await rawGet(url, pageHeaders(origin), timeoutMs);
  if (isGatePage(html)) {
    const g = await rawGet(origin + GATE_PATH, pageHeaders(origin), timeoutMs);
    const cm = g && g.match(/([A-Za-z0-9_]+)=IamOverEighteenYearsOld/);
    if (cm) ageCookie = cm[1] + '=IamOverEighteenYearsOld';
    html = await rawGet(url, pageHeaders(origin), timeoutMs);
  }
  return isGatePage(html) ? '' : html;
}

// 多域名 failover 取页：原域名优先，其余按 DOMAINS 顺序；首域 20s、后续域 12s（站方偶发 25s+ 慢响应）
async function getHtml(url) {
  const path = pathOf(url);
  const first = originOf(url) || SITE;
  const order = [first];
  for (const d of DOMAINS) if (d !== first) order.push(d);
  for (let i = 0; i < order.length; i++) {
    const html = await getHtmlForOrigin(order[i], path, i === 0 ? 20000 : 12000);
    if (html) return html;
  }
  return '';
}

// 列表解析：主循环 div.posts > div.post.video_9s（列表页 24 条、分类页 70 条；
// 注意站方用单引号写属性：<div class='post video_9s'>、<img src='...'>、<div class='meta'>、分页 <a href='...'>，
// 解析正则须同时接受单双引号，否则只剩容器 <div class="posts"> 一个切块、每页只出 1 条）；
// 每条 figure 链详情、h3 链标题、img 封面、.meta 日期。按 <div class="post 切块解析，
// 只取每块内第一个 _content 详情链，排除站内边栏/推荐混入。
function parsePosts(html) {
  const out = [];
  if (!html) return out;
  const seen = new Set();
  // 切块：<div class='post video_9s'>（各区）与 <div class='post'>（dt 区）两种写法；
  // 容器 <div class="posts"> 的 'post' 后跟 's'，不在 [\s'"] 内，不会被误切
  const chunks = String(html).split(/<div class=['"]post[\s'"]/);
  for (let i = 1; i < chunks.length; i++) {
    const c = chunks[i];
    const lm = c.match(/href=['"](https?:\/\/[^'"]*?_content\/[^'"]+?\.html)['"]/i);
    if (!lm) continue;
    const href = lm[1];
    if (seen.has(href)) continue;
    seen.add(href);
    const tm = c.match(/<h3[^>]*>\s*<a[^>]*>([^<]{2,400})<\/a>/i);
    const title = tm ? decodeHtml(tm[1]) : href;
    const pm = c.match(/<img[^>]+src=['"](https?:\/\/[^'"]+)['"]/i);
    const pic = pm ? pm[1] : '';
    const dm = c.match(/<div class=['"]meta['"]>([^<]*)<\/div>/i);
    out.push({ vod_id: href, vod_name: title, vod_pic: pic, vod_remarks: dm ? t(dm[1]) : '' });
  }
  return out;
}

// 真实总页数：取与当前列表同前缀的数字分页链接最大值；无分页器即单页
function parsePagecount(html, url) {
  if (!html) return 1;
  // 分页链接里题材名是原文 UTF-8（如 /8/巨乳癖/2.html），而请求 URL 里是 encodeURIComponent 后的
  // %E5%B7%A8...，比较前两边都 decode，否则分类页 pagecount 恒为 1
  let base = pathOf(url).replace(/\/\d+\.html$/, '/');
  try { base = decodeURIComponent(base); } catch (e) { /* ignore */ }
  let max = 1;
  const re = /href=['"]([^'"]*?\/(\d+)\.html)['"]/g;
  let m;
  while ((m = re.exec(html))) {
    let p = pathOf(m[1]);
    try { p = decodeURIComponent(p); } catch (e) { /* ignore */ }
    if (p.indexOf(base) !== 0) continue;
    const n = parseInt(m[2], 10);
    if (n > max && n < 100000) max = n;
  }
  return max;
}

